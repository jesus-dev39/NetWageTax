/**
 * Generates src/lib/us-state-paths.ts from the us-atlas (US Census Bureau
 * cartographic boundaries, pre-projected to Albers USA at 975×610).
 * Run with: npm run generate:map
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { presimplify, simplify, quantile } from 'topojson-simplify';
import { geoPath } from 'd3-geo';

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve('us-atlas/states-albers-10m.json'), 'utf8'));

const NAME_TO_CODE = {
  Alabama: 'AL', Alaska: 'AK', Arizona: 'AZ', Arkansas: 'AR', California: 'CA', Colorado: 'CO',
  Connecticut: 'CT', Delaware: 'DE', 'District of Columbia': 'DC', Florida: 'FL', Georgia: 'GA',
  Hawaii: 'HI', Idaho: 'ID', Illinois: 'IL', Indiana: 'IN', Iowa: 'IA', Kansas: 'KS', Kentucky: 'KY',
  Louisiana: 'LA', Maine: 'ME', Maryland: 'MD', Massachusetts: 'MA', Michigan: 'MI', Minnesota: 'MN',
  Mississippi: 'MS', Missouri: 'MO', Montana: 'MT', Nebraska: 'NE', Nevada: 'NV', 'New Hampshire': 'NH',
  'New Jersey': 'NJ', 'New Mexico': 'NM', 'New York': 'NY', 'North Carolina': 'NC', 'North Dakota': 'ND',
  Ohio: 'OH', Oklahoma: 'OK', Oregon: 'OR', Pennsylvania: 'PA', 'Rhode Island': 'RI',
  'South Carolina': 'SC', 'South Dakota': 'SD', Tennessee: 'TN', Texas: 'TX', Utah: 'UT', Vermont: 'VT',
  Virginia: 'VA', Washington: 'WA', 'West Virginia': 'WV', Wisconsin: 'WI', Wyoming: 'WY',
};

// Drop the finest detail (invisible at this size) to keep the bundle small.
const simplified = simplify(presimplify(topology), quantile(presimplify(topology), 0.35));
const states = feature(simplified, simplified.objects.states).features;
const path = geoPath().digits(1);

const entries = states
  .map((f) => {
    const code = NAME_TO_CODE[f.properties.name];
    if (!code) throw new Error(`Unmapped state: ${f.properties.name}`);
    const [cx, cy] = path.centroid(f).map((n) => Math.round(n));
    return { code, d: path(f), cx, cy };
  })
  .sort((a, b) => a.code.localeCompare(b.code));

if (entries.length !== 51) throw new Error(`Expected 51 shapes, got ${entries.length}`);

const body = entries
  .map(({ code, d, cx, cy }) => `  ${code}: { d: '${d}', cx: ${cx}, cy: ${cy} },`)
  .join('\n');

writeFileSync(
  new URL('../src/lib/us-state-paths.ts', import.meta.url),
  `// GENERATED by scripts/generate-state-paths.mjs. Do not edit by hand.
// Source: us-atlas states-albers-10m (US Census Bureau cartographic boundary files), Albers USA projection.

import type { StateCode } from './state-tax-data';

export const US_MAP_VIEWBOX = { width: 975, height: 610 } as const;

export const US_STATE_PATHS: Record<StateCode, { d: string; cx: number; cy: number }> = {
${body}
};
`,
);
console.log(`Wrote ${entries.length} state paths`);
